package Operators;

public class Unary {
    public static void  main(String[]args){
        int A = 40;
        int B = ++A;
        System.out.println(A);
        System.out.println(B);

        int C = 40;
        int D = --C;
        System.out.println(C);
        System.out.println(D);  
    }
}
