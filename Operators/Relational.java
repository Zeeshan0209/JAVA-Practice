package Operators;

public class Relational {
    public static void main(String[]args){
        int a = 10;
        int b = 80;
        int c = 30;
        int d = 10;
        System.out.println(a==d);
        System.out.println(a!=c);
        System.out.println(a<b);
        System.out.println(b>c);
        System.out.println(d<=a);
        System.out.println(c>=b);
    }
}
